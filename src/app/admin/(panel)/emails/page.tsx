import { query } from "@/lib/db";
import { PageHeader, Card, Chip, EmptyState } from "@/components/admin/ui";

export const dynamic = "force-dynamic";

type OutboxRow = {
  id: string;
  to_address: string;
  subject: string;
  template: string;
  body_html: string;
  status: string;
  created_at: string;
};

const TEMPLATE_LABELS: Record<string, string> = {
  order_confirmation: "Order confirmation",
  access_code: "Access code",
  vendor_drop_ship: "Vendor drop-ship",
};

export default async function EmailsPage() {
  const emails = await query<OutboxRow>(
    `select * from email_outbox order by created_at desc limit 100`
  );

  return (
    <>
      <PageHeader
        title="Emails"
        subtitle="Messages are rendered and recorded here rather than sent. Connecting a provider means dispatching queued rows."
      />

      {emails.length === 0 ? (
        <EmptyState>No emails yet.</EmptyState>
      ) : (
        <div className="space-y-3">
          {emails.map((e) => (
            <Card key={e.id} className="p-4">
              <details>
                <summary className="wx-focus flex cursor-pointer flex-wrap items-center gap-3 rounded">
                  <Chip tone="purple">{TEMPLATE_LABELS[e.template] ?? e.template}</Chip>
                  <span className="font-semibold">{e.subject}</span>
                  <span className="text-sm text-wx-muted">to {e.to_address}</span>
                  <span className="ml-auto text-xs text-wx-muted">
                    {new Date(e.created_at).toLocaleString("en-GB")}
                  </span>
                  <Chip tone={e.status === "sent" ? "green" : "amber"}>{e.status}</Chip>
                </summary>
                <div
                  className="mt-4 overflow-x-auto rounded-xl border border-wx-line bg-wx-bg p-3"
                  // Content is generated by our own templates in lib/email.
                  dangerouslySetInnerHTML={{ __html: e.body_html }}
                />
              </details>
            </Card>
          ))}
        </div>
      )}
    </>
  );
}
